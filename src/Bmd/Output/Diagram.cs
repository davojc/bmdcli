using System.Net;
using System.Text;

namespace Bmd.Output;

/// <summary>One endpoint on a device — an input, an output, a multiviewer window, an auxiliary.
/// <paramref name="Id"/> is unique across the whole page, because the browser needs to address
/// them all from one script.</summary>
public sealed record DiagramNode(string Id, string Badge, string Label);

/// <summary>A signal path inside one device: this source currently reaches that destination.</summary>
public sealed record DiagramLink(string From, string To);

/// <summary>One device's contribution to the page. <paramref name="Error"/> is set instead of the
/// rest when the device could not be reached — a diagram of a network is more useful with a gap
/// marked in it than with the device silently missing.</summary>
public sealed record DiagramDevice(
    string Title, string Subtitle, string Kind, string Host,
    IReadOnlyList<DiagramNode> Sources, IReadOnlyList<DiagramNode> Destinations,
    IReadOnlyList<DiagramLink> Links, IReadOnlyList<string> Facts, string? Error = null);

/// <summary>Renders every device bmd can reach as one self-contained HTML page.
///
/// <para><b>Self-contained means one file, not no script.</b> The page is emailed, opened from a
/// USB stick in a rack room, or printed and taped inside a cabinet door, so it fetches nothing:
/// no CDN, no web font, no external stylesheet. Its script and styles are inline, which costs
/// none of that and buys the thing a generator cannot do on its own — measure the laid-out page
/// and draw connectors between real positions, then light them up under the cursor.</para>
///
/// <para>Everything interpolated here is device-supplied text: an operator can name an input
/// <c>&lt;script&gt;</c> from a front panel, and this page opens in a browser. All of it goes
/// through <see cref="Text"/>, and the link data is emitted as JSON inside a
/// <c>&lt;script type="application/json"&gt;</c> block rather than as executable source, so a
/// label can never become code.</para></summary>
public static class Diagram
{
    public static string Render(IReadOnlyList<DiagramDevice> devices, DateTimeOffset generatedAt)
    {
        var page = new StringBuilder();
        var reachable = devices.Where(d => d.Error is null).ToList();

        page.Append($"""
            <!DOCTYPE html>
            <html lang="en">
            <head>
            <meta charset="utf-8">
            <meta name="viewport" content="width=device-width, initial-scale=1">
            <title>Signal flow</title>
            <style>
            {Css}
            </style>
            </head>
            <body>
            <main>
              <header class="top">
                <p class="eyebrow">Signal flow</p>
                <h1>{reachable.Count} device{(reachable.Count == 1 ? "" : "s")}</h1>
                <p class="stamp">As at {Text(generatedAt.ToString("yyyy-MM-dd HH:mm"))} UTC &middot; hover or tab a name to trace what it feeds</p>
              </header>

            """);

        foreach (var device in devices) AppendDevice(page, device);

        page.Append($"""
              <footer>Generated by bmd. Locks, and anything changed after the timestamp, are not shown.
              Connections are those inside each device; cabling between devices is not something a
              device reports.</footer>
            </main>
            <script>
            {Script}
            </script>
            </body>
            </html>

            """);

        return page.ToString();
    }

    static void AppendDevice(StringBuilder page, DiagramDevice device)
    {
        page.Append($"""
              <section class="device" data-kind="{Text(device.Kind)}">
                <header>
                  <h2>{Text(device.Title)}</h2>
                  <p class="sub">{Text(device.Subtitle)} &middot; {Text(device.Host)}</p>
                </header>

            """);

        if (device.Error is not null)
        {
            page.Append($"""
                <p class="unreachable">{Text(device.Error)}</p>
              </section>

            """);
            return;
        }

        if (device.Facts.Count > 0)
        {
            page.Append("    <ul class=\"facts\">\n");
            foreach (var fact in device.Facts)
                page.Append($"      <li>{Text(fact)}</li>\n");
            page.Append("    </ul>\n");
        }

        var fanOut = device.Links.GroupBy(l => l.From).ToDictionary(g => g.Key, g => g.Count());

        page.Append("""
                <div class="flow">
                  <ul class="col srcs">

            """);
        foreach (var node in device.Sources)
        {
            var fan = fanOut.GetValueOrDefault(node.Id, 0);
            page.Append($"""
                      <li data-node="{Text(node.Id)}" tabindex="0"><span class="num">{Text(node.Badge)}</span><span class="lbl">{Text(node.Label)}</span><span class="fan">{fan}</span></li>

                """);
        }

        page.Append("""
                  </ul>
                  <svg class="wires" aria-hidden="true"></svg>
                  <ul class="col dsts">

            """);
        foreach (var node in device.Destinations)
        {
            page.Append($"""
                      <li data-node="{Text(node.Id)}" tabindex="0"><span class="num">{Text(node.Badge)}</span><span class="lbl">{Text(node.Label)}</span></li>

                """);
        }

        // Links travel as data, never as generated script: a device label is untrusted text and
        // must not be able to reach a place where it would be parsed as code.
        page.Append($"""
                  </ul>
                </div>
                <script type="application/json" class="wire-data">{LinksJson(device.Links)}</script>
              </section>

            """);
    }

    /// <summary>Hand-built rather than serialized: the payload is two short strings per link, the
    /// ids are generated here so their shape is known, and this keeps the page's data out of the
    /// JSON source-generator contract that exists for command output.</summary>
    static string LinksJson(IReadOnlyList<DiagramLink> links)
    {
        var json = new StringBuilder("[");
        for (var i = 0; i < links.Count; i++)
        {
            if (i > 0) json.Append(',');
            json.Append($"[\"{Json(links[i].From)}\",\"{Json(links[i].To)}\"]");
        }
        return json.Append(']').ToString();
    }

    /// <summary>Ids are generated (`d0-in-3`), so this only has to be correct, not general.
    /// <c>&lt;/</c> is escaped because the string sits inside a script element.</summary>
    static string Json(string value)
    {
        var escaped = new StringBuilder();
        foreach (var c in value)
        {
            if (c is '"' or '\\') escaped.Append('\\').Append(c);
            else if (c == '<') escaped.Append("\\u003c");
            else if (c < ' ') escaped.Append($"\\u{(int)c:x4}");
            else escaped.Append(c);
        }
        return escaped.ToString();
    }

    static string Text(string value) => WebUtility.HtmlEncode(value);

    const string Css = """
        :root {
          --bg: #0c0d10; --panel: #14161a; --line: #24272e; --line-soft: #1c1f25;
          --fg: #e6e8ec; --dim: #989fab; --faint: #79818e; --signal: #f2542d;
          --mono: "IBM Plex Mono", ui-monospace, SFMono-Regular, Consolas, "Liberation Mono", monospace;
          --sans: "IBM Plex Sans", -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
        }
        * { box-sizing: border-box; }
        body { margin: 0; background: var(--bg); color: var(--fg); font-family: var(--sans); line-height: 1.5; }
        main { max-width: 78rem; margin: 0 auto; padding: 2.5rem 1.25rem 4rem; }
        .eyebrow { margin: 0 0 .4rem; font-family: var(--mono); font-size: .68rem; font-weight: 600;
          letter-spacing: .2em; text-transform: uppercase; color: var(--faint); }
        h1 { margin: 0; font-size: clamp(1.8rem, 4vw, 2.6rem); line-height: 1.05; letter-spacing: -.02em; }
        .stamp { margin: .45rem 0 0; font-family: var(--mono); font-size: .76rem; color: var(--faint); }
        .device { margin-top: 3rem; padding-top: 2rem; border-top: 1px solid var(--line-soft); }
        .device h2 { margin: 0; font-size: 1.45rem; letter-spacing: -.01em; }
        .device .sub { margin: .2rem 0 0; color: var(--dim); font-size: .92rem; }
        .facts { list-style: none; display: flex; flex-wrap: wrap; gap: .4rem; margin: .9rem 0 0; padding: 0; }
        .facts li { font-family: var(--mono); font-size: .68rem; letter-spacing: .04em; color: var(--faint);
          border: 1px solid var(--line); border-radius: 5px; padding: .18rem .45rem; }
        .unreachable { margin: 1rem 0 0; padding: .8rem 1rem; border: 1px solid var(--line);
          border-left: 2px solid var(--signal); border-radius: 8px; background: var(--panel); color: var(--dim); }
        .flow { position: relative; display: grid; grid-template-columns: 1fr 5.5rem 1fr;
          gap: 0; margin-top: 1.25rem; align-items: start; }
        .wires { position: absolute; inset: 0; width: 100%; height: 100%; pointer-events: none; overflow: visible; }
        .wires path { fill: none; stroke: var(--line); stroke-width: 1.25; transition: stroke .12s, opacity .12s; }
        .wires path.lit { stroke: var(--signal); stroke-width: 2; }
        .flow.tracing .wires path:not(.lit) { opacity: .18; }
        .col { list-style: none; margin: 0; padding: 0; display: grid; gap: .25rem; align-content: start; }
        .col li { display: flex; align-items: baseline; gap: .5rem; padding: .3rem .55rem;
          border: 1px solid transparent; border-radius: 7px; cursor: default; transition: background .12s, border-color .12s; }
        .col li:hover, .col li:focus-visible { outline: none; background: var(--panel); border-color: var(--line); }
        .col li.lit { background: var(--panel); border-color: var(--signal); }
        .flow.tracing .col li:not(.lit) { opacity: .3; }
        .srcs li { justify-content: flex-start; }
        .dsts li { flex-direction: row-reverse; text-align: right; }
        .num { font-family: var(--mono); font-size: .64rem; letter-spacing: .05em; color: var(--signal);
          border: 1px solid var(--line); border-radius: 4px; padding: .08rem .3rem; white-space: nowrap;
          font-variant-numeric: tabular-nums; flex: none; }
        .lbl { font-size: .92rem; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }
        .srcs .lbl { flex: 1; }
        .dsts .lbl { flex: 1; }
        .fan { font-family: var(--mono); font-size: .64rem; color: var(--faint); flex: none;
          font-variant-numeric: tabular-nums; }
        footer { margin-top: 3.5rem; padding-top: 1rem; border-top: 1px solid var(--line-soft);
          color: var(--faint); font-size: .8rem; max-width: 52rem; }
        @media (max-width: 46rem) {
          .flow { grid-template-columns: 1fr; gap: 1rem; }
          .wires { display: none; }
          .dsts li { flex-direction: row; text-align: left; }
        }
        @media (prefers-reduced-motion: reduce) { * { transition: none !important; } }
        @media print {
          body { background: #fff; color: #000; }
          .col li, .facts li, .unreachable { background: transparent; }
          .num { color: #000; }
          .wires path { stroke: #999; }
        }
        """;

    /// <summary>Draws the connectors and traces them on hover.
    ///
    /// The generator cannot place these: where a row lands depends on the font that resolved, the
    /// viewport, and how long the labels are. So the page measures itself after layout and again
    /// on resize. Without the script the columns still read correctly — the wires are the
    /// enhancement, not the content.</summary>
    const string Script = """
        (function () {
          var SVG = "http://www.w3.org/2000/svg";

          function build(section) {
            var flow = section.querySelector(".flow");
            var svg = section.querySelector(".wires");
            var data = section.querySelector(".wire-data");
            if (!flow || !svg || !data) return null;

            var links;
            try { links = JSON.parse(data.textContent); } catch (e) { return null; }

            var byNode = {};
            var paths = [];

            function draw() {
              while (svg.firstChild) svg.removeChild(svg.firstChild);
              paths.length = 0;
              for (var k in byNode) delete byNode[k];

              var box = flow.getBoundingClientRect();
              svg.setAttribute("viewBox", "0 0 " + box.width + " " + box.height);

              links.forEach(function (pair) {
                var a = flow.querySelector('[data-node="' + cssEscape(pair[0]) + '"]');
                var b = flow.querySelector('[data-node="' + cssEscape(pair[1]) + '"]');
                if (!a || !b) return;

                var ra = a.getBoundingClientRect(), rb = b.getBoundingClientRect();
                var x1 = ra.right - box.left, y1 = ra.top + ra.height / 2 - box.top;
                var x2 = rb.left - box.left, y2 = rb.top + rb.height / 2 - box.top;
                var bend = Math.max(24, (x2 - x1) / 2);

                var path = document.createElementNS(SVG, "path");
                path.setAttribute("d",
                  "M" + x1 + "," + y1 + " C" + (x1 + bend) + "," + y1 +
                  " " + (x2 - bend) + "," + y2 + " " + x2 + "," + y2);
                svg.appendChild(path);

                var record = { path: path, from: pair[0], to: pair[1] };
                paths.push(record);
                (byNode[pair[0]] = byNode[pair[0]] || []).push(record);
                (byNode[pair[1]] = byNode[pair[1]] || []).push(record);
              });
            }

            function trace(id) {
              var lit = byNode[id] || [];
              flow.classList.toggle("tracing", !!id);
              paths.forEach(function (r) { r.path.classList.remove("lit"); });
              Array.prototype.forEach.call(flow.querySelectorAll("li"), function (li) {
                li.classList.remove("lit");
              });
              if (!id) return;
              lit.forEach(function (r) {
                r.path.classList.add("lit");
                [r.from, r.to].forEach(function (n) {
                  var el = flow.querySelector('[data-node="' + cssEscape(n) + '"]');
                  if (el) el.classList.add("lit");
                });
              });
            }

            Array.prototype.forEach.call(flow.querySelectorAll("li[data-node]"), function (li) {
              var id = li.getAttribute("data-node");
              li.addEventListener("mouseenter", function () { trace(id); });
              li.addEventListener("mouseleave", function () { trace(null); });
              li.addEventListener("focus", function () { trace(id); });
              li.addEventListener("blur", function () { trace(null); });
            });

            return draw;
          }

          // Ids are generated by bmd and contain only [a-z0-9-], but the attribute selector is
          // built by string concatenation, so escape anyway rather than rely on that holding.
          function cssEscape(value) {
            return window.CSS && CSS.escape ? CSS.escape(value) : value.replace(/["\\]/g, "\\$&");
          }

          var redraws = [];
          Array.prototype.forEach.call(document.querySelectorAll(".device"), function (section) {
            var draw = build(section);
            if (draw) redraws.push(draw);
          });

          function drawAll() { redraws.forEach(function (d) { d(); }); }
          drawAll();
          // Fonts land after first paint and move every row; redraw once they have.
          if (document.fonts && document.fonts.ready) document.fonts.ready.then(drawAll);
          window.addEventListener("resize", drawAll);
        })();
        """;
}
